/** 混排列表：视频在前（更易点击），其后按发布日期倒序排图文 */
const FEED = VIDEOS.concat(
  ARTICLES.slice().sort((a, b) => (a.publishedAt < b.publishedAt ? 1 : -1))
)

/** 按 id 取单条 */
function byId(id) {
  const all = FEED.filter((x) => x.id === id)
  return all.length ? all[0] : null
}

/**
 * 列表页筛选
 * @param {string} category '全部' 或 CATEGORIES 中的一项
 * @param {string} type     'all' | 'article' | 'video'
 */
function filterFeed(category, type) {
  return FEED.filter((x) => {
    if (category && category !== '全部' && x.category !== category) return false
    if (type && type !== 'all' && x.type !== type) return false
    return true
  })
}

module.exports = { CATEGORIES, VIDEOS, ARTICLES, FEED, DISCLAIMER, byId, filterFeed }
